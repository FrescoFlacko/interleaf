import { mkdir, readdir, stat, unlink } from 'node:fs/promises';
import { join } from 'node:path';
import type { AgentContextPacket, AgentSession } from '@shared/types/agent';
import { AGENT_MAX_CONTEXT_PACKET_BYTES } from '@shared/schemas/agent';
import { InterleafError } from '@shared/errors/interleaf-error';
import type { AgentRepository } from '../db/repositories/agent-repository';
import type { AgentServiceLiveness } from './agent-service-liveness';
import type { OwnerOperation } from './agent-session-ownership';

const CONTEXT_PACKET_RETENTION_MS = 7 * 24 * 60 * 60 * 1_000;

export type AgentContextPacketsOptions = {
  readonly contextRoot: string;
  readonly repository: AgentRepository;
  readonly liveness: AgentServiceLiveness;
  readonly writeContextPacket: (path: string, data: string) => Promise<void>;
};

/**
 * Owns the bounded, app-owned context packet files a start hands to its
 * adapter, together with their artifact rows and retention sweep.
 */
export class AgentContextPackets {
  private readonly options: AgentContextPacketsOptions;

  constructor(options: AgentContextPacketsOptions) {
    this.options = options;
  }

  /** Writes the packet and records its artifact; returns the file path. */
  async persist(session: AgentSession, packet: AgentContextPacket, operation: OwnerOperation): Promise<string> {
    const { contextRoot, liveness, repository } = this.options;
    await mkdir(contextRoot, { recursive: true });
    const safeName = `${session.id}.json`;
    const path = join(contextRoot, safeName);
    const serialized = JSON.stringify(packet);
    const bytes = Buffer.byteLength(serialized, 'utf8');
    if (bytes > AGENT_MAX_CONTEXT_PACKET_BYTES) throw new InterleafError('validation', 'Agent context packet is too large.');
    try {
      await this.options.writeContextPacket(path, serialized);
      operation.assertLive();
      liveness.assertPersistenceWritable();
      repository.addArtifact({
        sessionId: session.id,
        kind: 'context_packet',
        appRelativePath: `agent-workspaces/context/${safeName}`,
        metadata: { bytes },
        expiresAt: new Date(Date.now() + CONTEXT_PACKET_RETENTION_MS).toISOString(),
      });
    } catch (error) {
      await unlink(path).catch(() => undefined);
      throw error;
    }
    return path;
  }

  /**
   * Context packets are retained only briefly. The directory is created by
   * resolveAppPaths before the runtime starts, so a missing or empty root is
   * the first-launch case rather than a failure.
   */
  async sweepExpired(): Promise<void> {
    try {
      const entries = await readdir(this.options.contextRoot);
      const cutoff = Date.now() - CONTEXT_PACKET_RETENTION_MS;
      for (const entry of entries) {
        if (/^[a-f0-9-]{36}\.json$/iu.test(entry)) await this.removeIfExpired(entry, cutoff);
      }
    } catch { /* app-owned context root may be empty on first launch */ }
    if (!this.options.liveness.isPersistenceClosed()) this.options.repository.expireContextArtifacts(new Date().toISOString());
  }

  private async removeIfExpired(entry: string, cutoff: number): Promise<void> {
    const file = join(this.options.contextRoot, entry);
    try {
      if ((await stat(file)).mtimeMs >= cutoff) return;
      await unlink(file);
      // Keep the SQLite artifact index in step with files removed by the
      // retention sweep. The filename is an opaque session UUID that was
      // generated by main, never supplied by the renderer.
      if (!this.options.liveness.isPersistenceClosed()) this.options.repository.deleteContextArtifacts(entry.slice(0, -'.json'.length));
    } catch { /* retention sweep is best effort */ }
  }
}
